"""Command-line interface:  uv run python -m fin <command>

  fin init                  create data folder, database tables and the field-encryption key
  fin doctor                check that everything is set up (never prints secret values)
  fin secret set NAME       store a secret in Windows Credential Manager (hidden input)
  fin secret delete NAME    remove a secret
  fin secret list           show which secrets are set
  fin plaid link            open a local page to connect a bank through Plaid Link
  fin plaid sandbox-link    link Plaid's fake test bank (sandbox only) and sync it
  fin snaptrade connect     open SnapTrade's portal to connect a brokerage (e.g. Fidelity)
  fin sync                  pull fresh data from every linked institution
  fin holdings              list brokerage positions
  fin cashflow              income vs spending, recurring charges, how much you can invest
  fin rules add|list|delete relabel transactions (e.g. Zelle to landlord = rent)
  fin planned add|list|delete  known upcoming expenses (tuition installments, repairs)
  fin owed add|list|settle  money someone owes you for charges on your card (not your debt)
  fin portfolio             allocation vs targets, concentration, gains (--new-money, --targets)
  fin research TICKER       12-point investment memo from public data (FRED, Finnhub, FMP)
  fin macro                 rates, inflation, unemployment (FRED)
  fin risk                  cash runway, crash scenarios, volatility (--new-money, --keep-cash, --pick)
  fin backup [setup|now|list|verify|restore]  encrypted backups of your data (no bank tokens)
  fin daily                 sync + backup in one go (what the scheduled task runs); --status
  fin schedule install|remove|status  run `fin daily` automatically every day (Task Scheduler)
  fin app                   open the local dashboard in your browser
  fin import apple-card     import Apple Card statement PDFs from the imports folder
  fin accounts              list accounts with their latest balances
"""

