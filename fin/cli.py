def cmd_rules(args: argparse.Namespace) -> int:
    from fin.db.models import CategoryRule

    init_db()
    with session_scope() as s:
        if args.action == "add":
            if not args.pattern or not args.category:
                print('Usage: fin rules add "landlord" RENT_AND_UTILITIES --label Rent --min 1000 --max 1000',
                      file=sys.stderr)
                return 2
            from decimal import Decimal

            r = CategoryRule(
                pattern=args.pattern.strip(), category=args.category.upper(), label=args.label,
                direction=args.direction,
                min_amount=Decimal(str(args.min)) if args.min is not None else None,
                max_amount=Decimal(str(args.max)) if args.max is not None else None,
            )
            s.add(r)
            s.flush()
            matches = s.scalars(select(Transaction)).all()
            from fin.analytics.rules import _words

            need = _words(r.pattern)
            def _in_range(t) -> bool:  # noqa: ANN001
                if (r.direction == "out" and t.amount > 0) or (r.direction == "in" and t.amount < 0):
                    return False
                a = abs(t.amount)
                return (r.min_amount is None or a >= r.min_amount) and (
                    r.max_amount is None or a <= r.max_amount)

            n = sum(1 for t in matches
                    if need <= _words(f"{t.merchant or ''} {t.description or ''}") and _in_range(t))
            print(f"Rule {r.id} added: '{r.pattern}' -> {r.category}"
                  f"{' (' + r.label + ')' if r.label else ''}. Matches {n} transaction(s).")
            if n == 0:
                print("  No matches - check spelling against `fin search <word>`.")
            return 0
        if args.action == "list":
            rows = s.scalars(select(CategoryRule).order_by(CategoryRule.id)).all()
            if not rows:
                print("No rules yet.")
            for r in rows:
                rng = ""
                if r.min_amount is not None or r.max_amount is not None:
                    rng = f"  amount {r.min_amount if r.min_amount is not None else 0:,.2f}-" + (
                        f"{r.max_amount:,.2f}" if r.max_amount is not None else "any")
                print(f"  [{r.id}] '{r.pattern}' -> {r.category}"
                      f"{'  (' + r.label + ')' if r.label else ''}{rng}"
                      f"{'  ' + r.direction + ' only' if r.direction else ''}")
            return 0
        if args.action == "delete":
            r = s.get(CategoryRule, int(args.pattern or 0))
            if r is None:
                print("No rule with that id.")
                return 1
            s.delete(r)
            print("Deleted.")
            return 0
    return 2


def cmd_search(args: argparse.Namespace) -> int:
    """Find transactions by a word, to see how your bank names them (for writing rules)."""
    init_db()
    word = args.word.lower()
    with session_scope() as s:
        rows = [t for t in s.scalars(select(Transaction).order_by(Transaction.date.desc()))
                if word in f"{t.merchant or ''} {t.description or ''}".lower()][: args.limit]
        for t in rows:
            print(f"  {t.date}  {t.amount:>10,.2f}  {(t.merchant or '')[:28]:28}  "
                  f"{(t.description or '')[:40]:40}  {t.category or ''}")
        if not rows:
            print("No matches.")
    return 0


def cmd_planned(args: argparse.Namespace) -> int:
    import datetime as dt
    from decimal import Decimal, InvalidOperation

    from fin.analytics.cashflow import _add_months
    from fin.db.models import PlannedExpense

    init_db()
    with session_scope() as s:
        if args.action == "add":
            if not (args.name and args.amount and args.date):
                print('Usage: fin planned add "Spring tuition" 1268.92 --date 2027-01-01 --repeat 4',
                      file=sys.stderr)
                return 2
            try:
                amount = Decimal(args.amount)
                first = dt.date.fromisoformat(args.date)
            except (InvalidOperation, ValueError):
                print("Amount must be a number and --date like 2027-01-01.", file=sys.stderr)
                return 2
            if amount <= 0:
                print("Amount must be positive (it's money you will pay).", file=sys.stderr)
                return 2
            for i in range(max(1, args.repeat)):
                y, m = _add_months(first.year, first.month, i)
                import calendar

                due = dt.date(y, m, min(first.day, calendar.monthrange(y, m)[1]))
                name = args.name if args.repeat <= 1 else f"{args.name} ({i + 1}/{args.repeat})"
                s.add(PlannedExpense(name=name, amount=amount, due_date=due,
                                     category=args.category.upper() if args.category else None))
                print(f"  added {due}  {name}  {amount:,.2f}")
            return 0
        if args.action == "list":
            rows = s.scalars(select(PlannedExpense).order_by(PlannedExpense.due_date)).all()
            if not rows:
                print("No planned expenses.")
            today = dt.date.today()
            for p in rows:
                past = "  (past)" if p.due_date < today else ""
                print(f"  [{p.id}] {p.due_date}  {p.name[:36]:36} {p.amount:>10,.2f}"
                      f"  {p.category or ''}{past}")
            return 0
        if args.action == "delete":
            p = s.get(PlannedExpense, int(args.name or 0))
            if p is None:
                print("No planned expense with that id.")
                return 1
            s.delete(p)
            print("Deleted.")
            return 0
    return 2


def cmd_owed(args: argparse.Namespace) -> int:
    from decimal import Decimal, InvalidOperation

    from fin.analytics.receivables import add_receivable, load_receivables, settle_receivable

    init_db()
    with session_scope() as s:
        if args.action == "add":
            if not (args.who and args.amount):
                print('Usage: fin owed add "Alex (roommate)" 510 --card chase --note "her charges"',
                      file=sys.stderr)
                return 2
            try:
                amount = Decimal(args.amount)
            except InvalidOperation:
                print("Amount must be a number, e.g. 510 or 510.00", file=sys.stderr)
                return 2
            if amount <= 0:
                print("Amount must be positive.", file=sys.stderr)
                return 2
            r = add_receivable(s, args.who, amount, card=args.card, note=args.note or "")
            where = f" on your {r.card} card" if r.card else ""
            print(f"  [{r.id}] {r.who} owes you {r.amount:,.2f}{where}. "
                  "It no longer counts as your debt.")
            return 0
        if args.action == "list":
            items = load_receivables(s)
            if not items:
                print("Nobody owes you anything right now.")
            for r in items:
                card = f"  card: {r.card}" if r.card else ""
                note = f"  ({r.note})" if r.note else ""
                print(f"  [{r.id}] {r.who:24} {r.amount:>10,.2f}  since {r.created}{card}{note}")
            return 0
        if args.action == "settle":
            try:
                rid = int(args.who or 0)
                part = Decimal(args.amount) if args.amount else None
            except (ValueError, InvalidOperation):
                print("Usage: fin owed settle ID [AMOUNT]   (amount = partial repayment)",
                      file=sys.stderr)
                return 2
            r = settle_receivable(s, rid, part)
            if r is None:
                print("No open item with that id. See: fin owed list")
                return 1
            if any(i.id == rid for i in load_receivables(s)):
                print(f"  Partial repayment recorded. {r.who} still owes {r.amount:,.2f}.")
            else:
                print(f"  Settled: {r.who} paid you back. Removed from the list.")
            return 0
    return 2


def cmd_portfolio(args: argparse.Namespace) -> int:
    from decimal import Decimal, InvalidOperation

    from fin.analytics.portfolio import BUCKETS, save_targets
    from fin.web.summary import portfolio

    init_db()
    if args.targets:
        try:
            targets = {}
            for part in args.targets.split(","):
                k, v = part.split("=")
                targets[k.strip()] = Decimal(v.strip())
            with session_scope() as s:
                save_targets(s, targets)
        except (ValueError, InvalidOperation) as exc:
            print(f"Targets not saved: {exc}. Example: --targets us_stock=70,intl_stock=20,"
                  f"single_stock=10   (buckets: {', '.join(BUCKETS)})", file=sys.stderr)
            return 2
        print("Targets saved.")
    p = portfolio(new_money=args.new_money or 0)

    def m(x):  # noqa: ANN001, ANN202
        return "-" if x is None else f"{x:,.2f}"

    print(f"Portfolio (as of {p['as_of'] or 'n/a'})")
    print(f"  Total {m(p['total'])}   invested {m(p['invested'])}   cash {m(p['cash'])}")
    print("\n  Allocation (cash excluded)      Value       Now   Target   Drift")
    for r in p["allocation"]:
        tgt = "-" if r["target_pct"] is None else f"{r['target_pct']:.0f}%"
        drift = "" if r["drift"] is None else f"{r['drift']:+.1f}"
        print(f"  {r['label'][:28]:28} {m(r['value']):>10} {r['pct']:>8.1f}% {tgt:>7} {drift:>7}")
    if p["top_positions"]:
        print("\n  Largest positions")
        for r in p["top_positions"]:
            print(f"  {r['ticker'][:8]:8} {r['name'][:30]:30} {m(r['value']):>10} {r['pct']:>6.1f}%")
    g = p["gains"]
    if g:
        pc = "" if g.get("gain_pct") is None else f" ({g['gain_pct']:+.1f}%)"
