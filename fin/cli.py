def cmd_init(_args: argparse.Namespace) -> int:
    settings = get_settings()
    settings.data_dir.mkdir(parents=True, exist_ok=True)
    tables = init_db()
    created_key = crypto.ensure_field_key()
    print(f"Data folder : {settings.data_dir}")
    print(f"Database    : {settings.db_path}  ({len(tables)} tables)")
    print(f"Field key   : {'created' if created_key else 'already present'} (in keyring)")
    print("Init complete.")
    return 0


def cmd_doctor(_args: argparse.Namespace) -> int:
    settings = get_settings()
    problems = 0

    def check(ok: bool, label: str, detail: str = "") -> None:
        nonlocal problems
        problems += 0 if ok else 1
        print(f"  [{'OK' if ok else '!!'}] {label}{(' - ' + detail) if detail else ''}")

    print(f"finintel {__version__} doctor")
    print("System")
    check(sys.version_info >= (3, 11), "Python", platform.python_version())
    check(True, "Platform", f"{platform.system()} {platform.release()}")
    backend = secrets.backend_name()
    check("fail" not in backend.lower(), "Keyring backend", backend)

    print("Storage")
    check(settings.data_dir.exists(), "Data folder", str(settings.data_dir))
    db_ok = settings.db_path.exists()
    check(db_ok, "Database file", str(settings.db_path))
    if db_ok:
        existing = set(inspect(get_engine()).get_table_names())
        missing = sorted(set(Base.metadata.tables) - existing)
        check(not missing, "Tables", "all present" if not missing else f"missing: {missing}")

    print("Settings")
    check(True, "Plaid environment", settings.plaid_env)
    check(bool(settings.sec_user_agent), "SEC User-Agent", settings.sec_user_agent or "not set in .env")

    print("Secrets (set / missing - values are never shown)")
    for name, is_set in secrets.status().items():
        print(f"  [{'set' if is_set else '---'}] {name}")

    print()
    print("All checks passed." if problems == 0 else f"{problems} problem(s) found.")
    return 0 if problems == 0 else 1


def cmd_secret(args: argparse.Namespace) -> int:
    if args.action == "list":
        for name, is_set in secrets.status().items():
            print(f"[{'set' if is_set else '---'}] {name:24} {secrets.KNOWN_SECRETS[name]}")
        return 0
    if not args.name:
        print("Secret name required.", file=sys.stderr)
        return 2
    if args.action == "set":
        if args.name == crypto.FIELD_KEY:
            print("db_field_key is generated by `fin init`; don't set it by hand.", file=sys.stderr)
            return 2
        if sys.stdin.isatty():
            value = getpass.getpass(f"Value for {args.name} (input hidden, right-click to paste): ")
        else:
            # Piped in, e.g.:  Get-Clipboard | uv run python -m fin secret set plaid_secret
            value = sys.stdin.readline()
        value = value.strip()
        if not value:
            print(
                "Nothing was received. Copy the value, then run:\n"
                f"  Get-Clipboard | uv run python -m fin secret set {args.name}",
                file=sys.stderr,
            )
            return 1
        if any(ch.isspace() for ch in value) or value.startswith("#"):
            print(
                "That doesn't look like a key (it contains spaces or starts with '#') - "
                "the clipboard probably held other text. Copy the key again and retry.",
                file=sys.stderr,
            )
            return 1
        expected = {"plaid_client_id": 24, "plaid_secret": 30, "plaid_secret_production": 30}.get(
            args.name
        )
        if expected and len(value) != expected:
            hint = ""
            n = len(value) // expected
            if len(value) % expected == 0 and n > 1 and value == value[:expected] * n:
                hint = f" It looks like the key was pasted {n} times - right-click only once."
            print(
                f"Not saved: Plaid's {args.name} is {expected} characters, got {len(value)}.{hint}",
                file=sys.stderr,
            )
            return 1
        if expected and not all(c in "0123456789abcdef" for c in value):
            print(f"Not saved: {args.name} should contain only 0-9 and a-f.", file=sys.stderr)
            return 1
        for other in secrets.KNOWN_SECRETS:
            if other != args.name and secrets.get_secret(other) == value:
                print(
                    f"Not saved: this is the same value already stored as '{other}'. "
                    "The clipboard probably still held the previous key - copy the right one.",
                    file=sys.stderr,
                )
                return 1
        secrets.set_secret(args.name, value)
        # Confirm without revealing: length and last 2 characters only.
        print(f"Saved {args.name} ({len(value)} characters, ending ...{value[-2:]}).")
        return 0
    if args.action == "delete":
        print("Deleted." if secrets.delete_secret(args.name) else "Not found.")
        return 0
    return 2


def _print_sync_results(results: list[dict]) -> int:
    if not results:
        print("No linked institutions yet.")
        return 0
    failed = 0
    for r in results:
        if r["status"] == "ok":
            print(
                f"  [OK] {r['institution']}: {r['accounts']} accounts, "
                f"{r['transactions_upserted']} transactions added/updated, "
                f"{r['transactions_removed']} removed"
                + (f"  (Plaid status: {r['update_status']})" if r.get("update_status") else "")
            )
            if r.get("update_status") == "NOT_READY":
                print("       Plaid is still preparing this bank's transactions - "
                      "run `uv run python -m fin sync` again in a minute or two.")
        else:
            failed += 1
            print(f"  [!!] {r['institution']}: {r['error']}")
    return 1 if failed else 0


def cmd_plaid(args: argparse.Namespace) -> int:
    from fin.providers.plaid_adapter import PlaidAdapter
    from fin.sync import link_plaid_item, run_plaid_sync

    settings = get_settings()
    if args.action == "link":
        from fin.link_server import serve

        serve(port=args.port, open_browser=not args.no_browser)
        return 0
    if args.action == "sandbox-link":
        if settings.plaid_env != "sandbox":
            print("sandbox-link only works with FIN_PLAID_ENV=sandbox.", file=sys.stderr)
            return 2
        init_db()
        adapter = PlaidAdapter()
        public_token = adapter.sandbox_public_token()
        with session_scope() as s:
            inst = link_plaid_item(s, adapter, public_token)
            print(f"Linked sandbox institution: {inst.name}")
        print("Syncing...")
        return _print_sync_results(run_plaid_sync(adapter=adapter))
    if args.action == "reset-cursor":
        from fin.sync import reset_plaid_cursors

        n = reset_plaid_cursors()
        print(f"Reset {n} cursor(s). Next sync re-reads full history (no duplicates are created).")
        return 0
    if args.action == "debug":
        # Read-only diagnostic: compares a from-scratch transactions call with the saved cursor.
        from fin import crypto
        from fin import secrets as sec
        from fin.db.models import SyncCursor

        adapter = PlaidAdapter()
        with session_scope() as s:
            for inst in s.scalars(select(Institution).where(Institution.provider == "plaid")):
                token = sec.require_secret(f"plaid_token:{crypto.decrypt(inst.provider_ref_enc)}")
                row = s.get(SyncCursor, (inst.id, "transactions"))
                saved = row.cursor if row else None
                print(f"{inst.name} (status={inst.status})")
                print(f"  saved cursor: {'none' if saved is None else ('empty' if saved == '' else f'{len(saved)} chars')}")
                for label, cur in (("from scratch", ""), ("from saved cursor", saved or "")):
                    page = adapter.transactions_sync(token, cur)
                    st = page.get("transactions_update_status")
                    print(f"  {label:18}: added={len(page.get('added') or [])} "
                          f"modified={len(page.get('modified') or [])} "
                          f"removed={len(page.get('removed') or [])} has_more={page.get('has_more')} "
                          f"status={getattr(st, 'value', st)} accounts_in_page={len(page.get('accounts') or [])}")
                    print(f"  {'':18}  page keys: {sorted(page.keys())}")
        return 0
    return 2


def _snaptrade_ready() -> bool:
    return bool(secrets.get_secret("snaptrade_client_id") and secrets.get_secret("snaptrade_consumer_key"))


def _print_snaptrade(results: list[dict]) -> int:
    if not results:
        print("  No brokerage accounts connected in SnapTrade yet (run: fin snaptrade connect).")
        return 0
    rc = 0
    for r in results:
        if "error" in r:
            rc = 1
            print(f"  [!!] {r['error']}")
        else:
            print(f"  [OK] {r['account']}: {r['positions']} positions, "
                  f"{r['activities_added']} new activities")
    return rc


def cmd_sync(_args: argparse.Namespace) -> int:
    from fin.sync import run_plaid_sync

    init_db()
    print("Plaid")
    rc = _print_sync_results(run_plaid_sync())
    if _snaptrade_ready():
        from fin.sync_snaptrade import run_snaptrade_sync

        print("SnapTrade")
        rc = max(rc, _print_snaptrade(run_snaptrade_sync()))
    return rc


def cmd_snaptrade(args: argparse.Namespace) -> int:
    import webbrowser

    from fin.providers.snaptrade_adapter import SnapTradeAdapter

    adapter = SnapTradeAdapter()
    if args.action == "connect":
        url = adapter.connection_url()
        print("Opening SnapTrade's Connection Portal (log in on your brokerage's own page;")
        print("choose read-only access). The link expires in about 5 minutes.")
        webbrowser.open(url)
        return 0
