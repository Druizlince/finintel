COPY_DIRS_KEY = "backup_copy_dirs"


def _backup_dirs() -> tuple["Path", list["Path"]]:  # noqa: F821
    import json
    from pathlib import Path

    from fin.db.models import Setting

    main = get_settings().data_dir / "backups"
    with session_scope() as s:
        row = s.get(Setting, COPY_DIRS_KEY)
        extra = [Path(p) for p in json.loads(row.value)] if row and row.value else []
    return main, extra


def run_backup(quiet: bool = False) -> "Path":  # noqa: F821
    import shutil

    from fin.backup import BackupError, PASS_SECRET, create_backup, prune

    pw = secrets.get_secret(PASS_SECRET)
    if not pw:
        raise BackupError("No backup passphrase yet. Run: uv run python -m fin backup setup")
    main, extra = _backup_dirs()
    path = create_backup(get_settings().db_path, main, pw, secrets.get_secret(crypto.FIELD_KEY))
    prune(main, keep=30)
    for d in extra:
        try:
            d.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, d / path.name)
            prune(d, keep=30)
        except OSError as exc:
            if not quiet:
                print(f"  ! could not copy to {d}: {exc}", file=sys.stderr)
    return path


def cmd_backup(args: argparse.Namespace) -> int:
    import json
    from pathlib import Path

    from fin.backup import BackupError, PASS_SECRET, check_passphrase, list_backups, restore_to, verify
    from fin.db.models import Setting

    init_db()
    action = args.action or "now"
    try:
        if action == "setup":
            if args.copy_to is not None:
                dirs = [str(Path(d).expanduser()) for d in args.copy_to if d]
                with session_scope() as s:
                    row = s.get(Setting, COPY_DIRS_KEY)
                    if row is None:
                        s.add(Setting(key=COPY_DIRS_KEY, value=json.dumps(dirs)))
                    else:
                        row.value = json.dumps(dirs)
                print("Backups will also be copied to: " + (", ".join(dirs) or "(nowhere else)"))
            if args.copy_to is None or not secrets.get_secret(PASS_SECRET):
                print("Choose a backup passphrase (12+ characters; a few random words is great).")
                print("SAVE IT in a password manager - without it, backups can't be opened.")
                p1 = getpass.getpass("Passphrase (hidden): ")
                check_passphrase(p1)
                if getpass.getpass("Repeat (hidden): ") != p1:
                    print("They don't match - nothing saved.", file=sys.stderr)
                    return 2
                secrets.set_secret(PASS_SECRET, p1)
                print("Passphrase saved in Windows Credential Manager.")
            return 0
        if action == "now":
            path = run_backup()
            print(f"Encrypted backup written: {path}")
            main, extra = _backup_dirs()
            if extra:
                print("Copied to: " + ", ".join(str(d) for d in extra))
            else:
                print("Tip: keep a copy off this laptop:  fin backup setup --copy-to "
                      "\"C:\\Users\\you\\OneDrive\\finintel-backups\"")
            return 0
        main, _ = _backup_dirs()
        if action == "list":
            files = list_backups(main)
            if not files:
                print("No backups yet. Run: uv run python -m fin backup")
            for f in files:
                print(f"  {f.name}  {f.stat().st_size / 1e6:.2f} MB")
            return 0
        pw = secrets.get_secret(PASS_SECRET) or getpass.getpass("Backup passphrase (hidden): ")
        if action == "verify":
            target = Path(args.file) if args.file else (list_backups(main) or [None])[0]
            if target is None:
                print("No backups to verify.")
                return 1
            info = verify(target, pw)
            print(f"OK: {Path(info['file']).name} from {info['created']} - integrity {info['integrity']}, "
                  f"{info['transactions']} transactions, {info['size_mb']} MB")
            return 0 if info["integrity"] == "ok" else 1
        if action == "restore":
            if not (args.file and args.to):
                print("Usage: fin backup restore FILE --to C:\\path\\restored.db", file=sys.stderr)
                return 2
            meta = restore_to(Path(args.file), pw, Path(args.to))
            print(f"Restored the {meta['created']} backup to {args.to}.")
            print("To use it: close the dashboard and Claude, then replace fin.db in your "
                  f"data folder ({get_settings().data_dir}) with this file.")
            if meta.get("field_key") and meta["field_key"] != secrets.get_secret(crypto.FIELD_KEY):
                print("This backup came from another computer. Before replacing, run once:\n"
                      "  uv run python -m fin secret set db_field_key   (value printed below)\n"
                      "then re-link banks (fin plaid link) and re-enter API keys.")
                print(f"  field key: {meta['field_key']}")
            return 0
    except BackupError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    return 2


def cmd_daily(args: argparse.Namespace) -> int:
    import datetime as dt
    import logging

    from fin.scheduler import load_status, save_status

    init_db()
    if args.status:
        with session_scope() as s:
            st = load_status(s)
        if not st:
            print("The daily job hasn't run yet.")
            return 0
        print(f"Last daily run: {st['finished']}  sync {'OK' if st['sync_ok'] else 'had errors'}"
              f"  backup {st.get('backup') or 'FAILED'}")
        for e in st.get("errors", []):
            print(f"  ! {e}")
        return 0
    log = logging.getLogger("fin.daily")
    errors: list[str] = []
    started = dt.datetime.now().isoformat(timespec="seconds")
    sync_ok = True
    try:
        from fin.sync import run_plaid_sync

        for r in run_plaid_sync():
            if r.get("status") != "ok":
                sync_ok = False
                errors.append(f"{r.get('institution')}: {r.get('error') or r.get('status')}")
        if _snaptrade_ready():
            from fin.sync_snaptrade import run_snaptrade_sync

            run_snaptrade_sync()
    except Exception as exc:  # noqa: BLE001 - the backup must still run
        sync_ok = False
        errors.append(f"sync: {type(exc).__name__}: {exc}")
    backup_name = None
    try:
        backup_name = run_backup(quiet=True).name
    except Exception as exc:  # noqa: BLE001
        errors.append(f"backup: {exc}")
    status = {"started": started, "finished": dt.datetime.now().isoformat(timespec="seconds"),
              "sync_ok": sync_ok, "backup": backup_name, "errors": errors}
    with session_scope() as s:
        save_status(s, status)
    (log.warning if errors else log.info)("daily run: sync_ok=%s backup=%s errors=%d",
                                          sync_ok, backup_name, len(errors))
    print(f"Sync {'OK' if sync_ok else 'had errors'}; backup {backup_name or 'FAILED'}")
    for e in errors:
        print(f"  ! {e}")
    return 0 if not errors else 1


def cmd_schedule(args: argparse.Namespace) -> int:
    from fin import scheduler

    if platform.system() != "Windows":
        print("Scheduling uses Windows Task Scheduler; run this on your Windows laptop.")
        return 2
    try:
        if args.action == "install":
            print(scheduler.install(args.time))
            print("Make sure a backup passphrase is set first: uv run python -m fin backup setup")
        elif args.action == "remove":
            print(scheduler.remove())
        else:
            print(scheduler.query())
    except (RuntimeError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    return 0


